-- Один источник данных для каталога: сумма остатков и скидка от даты сервера.
-- «Прошлый календарный месяц» НЕ равен «последние 30 дней».
CREATE VIEW dbo.vCatalog
AS
SELECT p.Id, p.Name, p.Description, p.Composition, p.ImageFile,
       p.CategoryId, c.Name AS Category,
       p.SubcategoryId, sc.Name AS Subcategory,
       p.ManufacturerId, m.Name AS Manufacturer, p.Price AS BasePrice,
       ISNULL((SELECT SUM(s.Quantity) FROM dbo.Stock s WHERE s.ProductId=p.Id),0) AS TotalQuantity,
       CASE WHEN NOT EXISTS (
           SELECT 1
           FROM dbo.OrderItems oi
           JOIN dbo.Stock st ON st.Id=oi.StockId
           JOIN dbo.Orders o ON o.Id=oi.OrderId
           WHERE st.ProductId=p.Id
             AND o.OrderDate>=DATEADD(month,-1,DATEFROMPARTS(YEAR(GETDATE()),MONTH(GETDATE()),1))
             AND o.OrderDate<DATEFROMPARTS(YEAR(GETDATE()),MONTH(GETDATE()),1)
       ) THEN CAST(ROUND(p.Price*0.75,2) AS decimal(12,2)) ELSE p.Price END AS FinalPrice,
       CASE WHEN NOT EXISTS (
           SELECT 1
           FROM dbo.OrderItems oi
           JOIN dbo.Stock st ON st.Id=oi.StockId
           JOIN dbo.Orders o ON o.Id=oi.OrderId
           WHERE st.ProductId=p.Id
             AND o.OrderDate>=DATEADD(month,-1,DATEFROMPARTS(YEAR(GETDATE()),MONTH(GETDATE()),1))
             AND o.OrderDate<DATEFROMPARTS(YEAR(GETDATE()),MONTH(GETDATE()),1)
       ) THEN 25 ELSE 0 END AS DiscountPercent
FROM dbo.Products p
JOIN dbo.Categories c ON p.CategoryId=c.Id
JOIN dbo.Subcategories sc ON p.SubcategoryId=sc.Id
JOIN dbo.Manufacturers m ON p.ManufacturerId=m.Id;
GO


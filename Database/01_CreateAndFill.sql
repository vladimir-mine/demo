CREATE TABLE dbo.Categories (
    Id int NOT NULL PRIMARY KEY,
    Name nvarchar(100) NOT NULL UNIQUE
);
CREATE TABLE dbo.Subcategories (
    Id int NOT NULL PRIMARY KEY,
    Name nvarchar(100) NOT NULL UNIQUE
);
CREATE TABLE dbo.Manufacturers (
    Id int NOT NULL PRIMARY KEY,
    Name nvarchar(150) NOT NULL UNIQUE
);
CREATE TABLE dbo.Sizes (
    Id int NOT NULL PRIMARY KEY,
    Value decimal(4,1) NOT NULL UNIQUE
);
CREATE TABLE dbo.Roles (
    Id int NOT NULL PRIMARY KEY,
    Name nvarchar(100) NOT NULL UNIQUE
);
CREATE TABLE dbo.Users (
    Id int NOT NULL PRIMARY KEY,
    Surname nvarchar(100) NOT NULL,
    FirstName nvarchar(100) NOT NULL,
    Patronymic nvarchar(100) NOT NULL DEFAULT N'',
    Login nvarchar(100) NOT NULL UNIQUE,
    RoleId int NOT NULL REFERENCES dbo.Roles(Id)
);
CREATE TABLE dbo.Products (
    Id int NOT NULL PRIMARY KEY,
    CategoryId int NOT NULL REFERENCES dbo.Categories(Id),
    SubcategoryId int NOT NULL REFERENCES dbo.Subcategories(Id),
    ManufacturerId int NOT NULL REFERENCES dbo.Manufacturers(Id),
    ImageFile nvarchar(200) NOT NULL DEFAULT N'',
    Name nvarchar(250) NOT NULL,
    Description nvarchar(max) NOT NULL,
    Composition nvarchar(max) NOT NULL,
    Price decimal(12,2) NOT NULL CHECK(Price>=0)
);
CREATE TABLE dbo.Stock (
    Id int NOT NULL PRIMARY KEY,
    ProductId int NOT NULL REFERENCES dbo.Products(Id),
    SizeId int NOT NULL REFERENCES dbo.Sizes(Id),
    Quantity int NOT NULL CHECK(Quantity>=0),
    CONSTRAINT UQ_Stock_ProductSize UNIQUE(ProductId,SizeId)
);
CREATE TABLE dbo.Orders (
    Id int IDENTITY(1,1) NOT NULL PRIMARY KEY,
    OrderDate datetime2(0) NOT NULL,
    UserId int NOT NULL REFERENCES dbo.Users(Id)
);
CREATE TABLE dbo.OrderItems (
    Id int IDENTITY(1,1) NOT NULL PRIMARY KEY,
    OrderId int NOT NULL REFERENCES dbo.Orders(Id),
    StockId int NOT NULL REFERENCES dbo.Stock(Id),
    Quantity int NOT NULL CHECK(Quantity>0),
    UnitPrice decimal(12,2) NOT NULL CHECK(UnitPrice>=0)
);
GO

